CREATE TABLE market_activity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id BIGINT NOT NULL,
    activity_date DATE NOT NULL,
    study_minutes BIGINT NOT NULL DEFAULT 0,
    study_sessions INTEGER NOT NULL DEFAULT 0,
    active_students INTEGER NOT NULL DEFAULT 0,
    completed_goals INTEGER NOT NULL DEFAULT 0,
    buy_volume NUMERIC(19, 4) NOT NULL DEFAULT 0,
    sell_volume NUMERIC(19, 4) NOT NULL DEFAULT 0,
    buy_transactions INTEGER NOT NULL DEFAULT 0,
    sell_transactions INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_market_activity_asset FOREIGN KEY (asset_id) REFERENCES assets (id),
    CONSTRAINT market_activity_asset_date_unique UNIQUE (asset_id, activity_date),
    CONSTRAINT market_activity_non_negative CHECK (
        study_minutes >= 0 AND study_sessions >= 0 AND active_students >= 0 AND completed_goals >= 0
        AND buy_volume >= 0 AND sell_volume >= 0 AND buy_transactions >= 0 AND sell_transactions >= 0
    )
);
CREATE INDEX idx_market_activity_asset_date ON market_activity (asset_id, activity_date);
CREATE INDEX idx_market_activity_date ON market_activity (activity_date);