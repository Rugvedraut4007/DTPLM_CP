CREATE TABLE asset_study_progress (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    asset_id BIGINT NOT NULL,
    target_minutes INTEGER NOT NULL DEFAULT 600,
    completed_minutes INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_asset_study_progress_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_asset_study_progress_asset FOREIGN KEY (asset_id) REFERENCES assets (id),
    CONSTRAINT asset_study_progress_user_asset_unique UNIQUE (user_id, asset_id),
    CONSTRAINT asset_study_progress_target_positive CHECK (target_minutes > 0),
    CONSTRAINT asset_study_progress_completed_non_negative CHECK (completed_minutes >= 0)
);

CREATE INDEX idx_asset_study_progress_user ON asset_study_progress (user_id);
CREATE INDEX idx_asset_study_progress_asset ON asset_study_progress (asset_id);