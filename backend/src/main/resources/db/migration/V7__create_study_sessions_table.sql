CREATE TABLE study_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    asset_id BIGINT NOT NULL,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    ended_at TIMESTAMP WITH TIME ZONE,
    duration_seconds BIGINT,
    status VARCHAR(9) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_study_sessions_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_study_sessions_asset FOREIGN KEY (asset_id) REFERENCES assets (id),
    CONSTRAINT study_sessions_status_check CHECK (status IN ('ACTIVE', 'COMPLETED')),
    CONSTRAINT study_sessions_completed_fields_check CHECK (
        (status = 'ACTIVE' AND ended_at IS NULL AND duration_seconds IS NULL)
        OR (status = 'COMPLETED' AND ended_at IS NOT NULL AND duration_seconds IS NOT NULL AND duration_seconds >= 0)
    )
);

CREATE INDEX idx_study_sessions_user ON study_sessions (user_id);
CREATE INDEX idx_study_sessions_asset ON study_sessions (asset_id);
CREATE INDEX idx_study_sessions_user_status ON study_sessions (user_id, status);