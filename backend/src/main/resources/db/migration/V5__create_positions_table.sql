CREATE TABLE positions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    asset_id BIGINT NOT NULL,
    quantity NUMERIC(19, 8) NOT NULL,
    average_buy_price NUMERIC(19, 4) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_positions_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_positions_asset FOREIGN KEY (asset_id) REFERENCES assets (id),
    CONSTRAINT positions_quantity_positive CHECK (quantity > 0),
    CONSTRAINT positions_user_asset_unique UNIQUE (user_id, asset_id)
);