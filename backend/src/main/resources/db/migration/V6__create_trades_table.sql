CREATE TABLE trades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    asset_id BIGINT NOT NULL,
    side VARCHAR(4) NOT NULL,
    quantity NUMERIC(19, 8) NOT NULL,
    price NUMERIC(19, 4) NOT NULL,
    total_value NUMERIC(19, 4) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_trades_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_trades_asset FOREIGN KEY (asset_id) REFERENCES assets (id),
    CONSTRAINT trades_side_buy_only CHECK (side = 'BUY'),
    CONSTRAINT trades_quantity_positive CHECK (quantity > 0)
);