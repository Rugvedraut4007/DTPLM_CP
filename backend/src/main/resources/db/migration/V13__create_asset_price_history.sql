CREATE TABLE asset_price_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id BIGINT NOT NULL,
    price NUMERIC(19, 4) NOT NULL,
    recorded_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    market_score NUMERIC(10, 4) NOT NULL,
    price_change_percent NUMERIC(10, 4) NOT NULL,
    CONSTRAINT fk_asset_price_history_asset FOREIGN KEY (asset_id) REFERENCES assets (id),
    CONSTRAINT asset_price_history_price_positive CHECK (price > 0)
);

CREATE INDEX idx_asset_price_history_asset_recorded ON asset_price_history (asset_id, recorded_at);